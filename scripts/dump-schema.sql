-- Regenerate schema/baseline.sql from the live database.
--
-- Run in the Supabase SQL editor (or any SQL client as postgres) and save
-- the single `ddl` value it returns as schema/baseline.sql. It reads only
-- the system catalogs: no row data, no secrets.
--
-- Covers the public schema (types, sequences, tables, constraints,
-- functions, views, indexes, triggers, RLS policies, grants), the signup
-- trigger on auth.users, Realtime publication membership, storage buckets
-- and storage policies. Supabase's own schemas (auth, storage tables,
-- realtime, vault, ...) come with every project and are not dumped.

-- Empty search path, so every name in the output is schema-qualified and
-- the baseline doesn't depend on the loader's search path.
SET search_path = '';

with
rel as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.reloptions, c.relacl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
fn as (
  select p.oid, p.proname, p.prokind, p.proacl, p.proowner,
         format('public.%I(%s)', p.proname, pg_get_function_identity_arguments(p.oid)) as sig
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
sec_extensions as (
  select string_agg(format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname), E'\n' order by e.extname) as s
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname not in ('plpgsql')
),
sec_types as (
  select string_agg(format('DO $t$ BEGIN CREATE TYPE public.%I AS ENUM (%s); EXCEPTION WHEN duplicate_object THEN NULL; END $t$;',
           t.typname,
           (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)),
         E'\n' order by t.typname) as s
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
),
sec_sequences as (
  select string_agg(format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s%s;',
           r.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax, s.seqstart,
           case when s.seqcycle then ' CYCLE' else '' end),
         E'\n' order by r.relname) as s
  from rel r join pg_sequence s on s.seqrelid = r.oid
  where r.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = r.oid and d.deptype = 'i')  -- identity sequences come with their column
),
sec_tables as (
  select string_agg(t.ddl, E'\n\n' order by t.relname) as s
  from (
    select r.relname,
      format(E'CREATE TABLE IF NOT EXISTS public.%I (\n    %s\n);', r.relname,
        string_agg(
          format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
          || case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
          || case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                  when ad.adbin is not null then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
                  else '' end
          || case when a.attnotnull then ' NOT NULL' else '' end,
          E',\n    ' order by a.attnum)) as ddl
    from rel r
    join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = r.oid and ad.adnum = a.attnum
    where r.relkind in ('r', 'p')
    group by r.relname
  ) t
),
sec_sequence_owners as (
  select string_agg(format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, t.relname, a.attname), E'\n' order by s.relname) as s
  from rel s
  join pg_depend d on d.objid = s.oid and d.deptype = 'a' and d.refobjsubid > 0
  join pg_class t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where s.relkind = 'S'
),
con as (
  select r.relname, c.conname, c.contype, pg_get_constraintdef(c.oid) as def
  from pg_constraint c join rel r on r.oid = c.conrelid
  where c.contype in ('p', 'u', 'c', 'x', 'f')
),
sec_constraints as (
  select string_agg(format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', relname, conname, def), E'\n'
         order by relname, case contype when 'p' then 0 when 'u' then 1 else 2 end, conname) as s
  from con where contype <> 'f'
),
sec_foreign_keys as (
  select string_agg(format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', relname, conname, def), E'\n' order by relname, conname) as s
  from con where contype = 'f'
),
sec_functions as (
  select string_agg(pg_get_functiondef(f.oid) || ';', E'\n\n' order by f.proname, f.sig) as s
  from fn f
),
sec_views as (
  select string_agg(
           case when r.relkind = 'm'
             then format(E'CREATE MATERIALIZED VIEW IF NOT EXISTS public.%I AS\n%s\nWITH NO DATA;', r.relname, rtrim(pg_get_viewdef(r.oid, true), ';'))
             else format(E'CREATE OR REPLACE VIEW public.%I%s AS\n%s;', r.relname,
                    case when r.reloptions is not null then ' WITH (' || array_to_string(r.reloptions, ', ') || ')' else '' end,
                    rtrim(pg_get_viewdef(r.oid, true), ';'))
           end,
         E'\n\n' order by r.oid) as s  -- creation order keeps views that use other views after them
  from rel r where r.relkind in ('v', 'm')
),
sec_indexes as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by r.relname, ic.relname) as s
  from pg_index i
  join rel r on r.oid = i.indrelid
  join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid and c.contype in ('p', 'u', 'x'))
),
sec_triggers as (
  select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by n.nspname, c.relname, t.tgname) as s
  from pg_trigger t
  join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal
    and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
),
sec_rls as (
  select string_agg(format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', relname)
           || case when relforcerowsecurity then format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', relname) else '' end,
         E'\n' order by relname) as s
  from rel where relkind in ('r', 'p') and relrowsecurity
),
pol as (
  select n.nspname, c.relname, p.polname,
    format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
      p.polname, n.nspname, c.relname,
      case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
      case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
      case when p.polroles = '{0}' then 'public'
           else (select string_agg(quote_ident(ro.rolname), ', ' order by ro.rolname) from pg_roles ro where ro.oid = any(p.polroles)) end,
      coalesce(E'\n    USING (' || pg_get_expr(p.polqual, p.polrelid) || ')', ''),
      coalesce(E'\n    WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', '')) as ddl
  from pg_policy p
  join pg_class c on c.oid = p.polrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public', 'storage')
),
sec_policies as (
  select string_agg(ddl, E'\n\n' order by relname, polname) as s from pol where nspname = 'public'
),
api_roles as (select unnest(array['anon', 'authenticated', 'service_role']) as rolname),
sec_grants as (
  select string_agg(g, E'\n' order by ord, obj, g) as s from (
    -- tables, views, sequences: reset, then grant exactly what the live database has
    select 1 as ord, r.relname as obj,
      format('REVOKE ALL ON %s public.%I FROM anon, authenticated, service_role;', case when r.relkind = 'S' then 'SEQUENCE' else 'TABLE' end, r.relname) as g
    from rel r where r.relkind in ('r', 'p', 'v', 'm', 'S')
    union all
    select 2, r.relname,
      format('GRANT %s ON %s public.%I TO %I;', string_agg(x.privilege_type, ', ' order by x.privilege_type),
             case when r.relkind = 'S' then 'SEQUENCE' else 'TABLE' end, r.relname, ro.rolname)
    from rel r
    cross join lateral aclexplode(r.relacl) x
    join pg_roles ro on ro.oid = x.grantee and ro.rolname in (select rolname from api_roles)
    where r.relkind in ('r', 'p', 'v', 'm', 'S') and r.relacl is not null
    group by r.relname, r.relkind, ro.rolname
    union all
    -- column-level grants
    select 3, r.relname,
      format('GRANT %s (%I) ON TABLE public.%I TO %I;', x.privilege_type, a.attname, r.relname, ro.rolname)
    from rel r
    join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
    cross join lateral aclexplode(a.attacl) x
    join pg_roles ro on ro.oid = x.grantee and ro.rolname in (select rolname from api_roles)
    union all
    -- functions: reset, then grant EXECUTE as the live database has it
    select 4, f.sig, format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', f.sig)
    from fn f
    union all
    select 5, f.sig,
      format('GRANT EXECUTE ON FUNCTION %s TO %s;', f.sig, case when x.grantee = 0 then 'PUBLIC' else quote_ident(ro.rolname) end)
    from fn f
    cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) x
    left join pg_roles ro on ro.oid = x.grantee
    where x.privilege_type = 'EXECUTE' and (x.grantee = 0 or ro.rolname in (select rolname from api_roles))
  ) grants
),
sec_realtime as (
  select string_agg(format(
           'DO $r$ BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.%I; EXCEPTION WHEN duplicate_object THEN NULL; END $r$;',
           tablename), E'\n' order by tablename) as s
  from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public'
),
sec_storage as (
  select concat_ws(E'\n\n',
    (select string_agg(format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;',
              b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'NULL'),
              coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL')),
            E'\n' order by b.id)
     from storage.buckets b),
    (select string_agg(ddl, E'\n\n' order by relname, polname) from pol where nspname = 'storage')) as s
)
select concat_ws(E'\n\n',
  E'-- Gather database schema baseline: the live public schema, generated by\n'
  || E'-- scripts/dump-schema.sql. Load into a fresh Supabase project to rebuild\n'
  || E'-- the database (no data). Not a migration: do not run it against production.\n'
  || E'--\n'
  || E'-- Also needed, not part of the schema: the Vault secret ip_hash_salt\n'
  || E'-- (same value as IP_HASH_SALT in Vercel), and the edge functions in\n'
  || E'-- supabase/functions.\n\n'
  || E'SET check_function_bodies = false;\nSET client_min_messages = warning;',
  '-- Extensions' || E'\n' || (select s from sec_extensions),
  '-- Types' || E'\n' || (select s from sec_types),
  '-- Sequences' || E'\n' || (select s from sec_sequences),
  '-- Tables' || E'\n' || (select s from sec_tables),
  '-- Primary keys, unique and check constraints' || E'\n' || (select s from sec_constraints),
  '-- Sequence ownership' || E'\n' || (select s from sec_sequence_owners),
  '-- Functions' || E'\n' || (select s from sec_functions),
  '-- Views' || E'\n' || (select s from sec_views),
  '-- Indexes' || E'\n' || (select s from sec_indexes),
  '-- Foreign keys' || E'\n' || (select s from sec_foreign_keys),
  '-- Triggers' || E'\n' || (select s from sec_triggers),
  '-- Row level security' || E'\n' || (select s from sec_rls),
  '-- Policies' || E'\n' || (select s from sec_policies),
  '-- Grants' || E'\n' || (select s from sec_grants),
  '-- Realtime' || E'\n' || (select s from sec_realtime),
  '-- Storage buckets and policies' || E'\n' || (select s from sec_storage)
) || E'\n' as ddl;
